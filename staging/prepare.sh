#!/bin/bash
# Prepares the staging cluster: builds the jars if they are missing, creates the secrets (once), and renders every config into data/.
# It only reads the shipped sample configs and changes the values a cluster on one Docker network needs, so what is tested here is the config
# you will ship. Run it again after changing the code; the secrets and the database stay.   Usage: staging/prepare.sh [--reset]
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
data="$here/data"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [ "${1:-}" = "--reset" ]; then
	rm -rf "$data" "$here/.env"
	echo "Removed data/ and .env"
fi

velocity_jar="$root/authenticator-velocity/target/Authenticator-Velocity-1.0.0.jar"
paper_jar="$root/authenticator-paper/target/Authenticator-Paper-1.0.0.jar"

if [ ! -f "$velocity_jar" ] || [ ! -f "$paper_jar" ]; then
	echo "Building the jars..."
	(cd "$root" && mvn -q package -DskipTests)
fi

"$root/tools/check-jars.sh"

random() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1" || true; }

if [ ! -f "$here/.env" ]; then
	cat >"$here/.env" <<ENV
# Generated by prepare.sh. Staging only: never reuse these.
DB_ROOT_PASSWORD=$(random 24)
DB_PROXY_PASSWORD=$(random 24)
DB_BACKEND_PASSWORD=$(random 24)
BRIDGE_SECRET=$(random 40)
FORWARDING_SECRET=$(random 24)
# PAPER_VERSION=26.2
ENV
	echo "Wrote .env"
fi

set -a
# shellcheck disable=SC1091
. "$here/.env"
set +a

# Changes single values of a YAML file that is written the way the shipped samples are, keeping every comment. Each replacement is
# "section.sub.key=value"; the value is written as given. A replacement that matches nothing is an error, so a renamed key cannot slip by.
render() {
	local source="$1" target="$2"
	shift 2
	mkdir -p "$(dirname "$target")"
	awk -v replacements="$(printf '%s\n' "$@")" '
		BEGIN {
			n = split(replacements, lines, "\n")
			for (i = 1; i <= n; i++) {
				eq = index(lines[i], "=")
				if (eq > 0) { want[substr(lines[i], 1, eq - 1)] = substr(lines[i], eq + 1); used[substr(lines[i], 1, eq - 1)] = 0 }
			}
		}
		{
			if (match($0, /^ *[A-Za-z_-]+:/)) {
				indent = match($0, /[^ ]/) - 1
				key = $0; sub(/^ */, "", key); sub(/:.*$/, "", key)
				depth = indent / 2
				path[depth] = key
				for (d in path) if (d + 0 > depth) delete path[d]
				full = path[0]
				for (d = 1; d <= depth; d++) full = full "." path[d]
				if (full in want) {
					printf "%*s%s: %s\n", indent, "", key, want[full]
					used[full] = 1
					next
				}
			}
			print
		}
		END {
			for (k in used) if (!used[k]) { print "no such key in " FILENAME ": " k > "/dev/stderr"; bad = 1 }
			exit bad
		}' "$source" >"$target"
}

# MariaDB: the accounts, with this staging cluster's passwords
mkdir -p "$data/mariadb-init"
sed -e "s|@AUTH_PROXY_PASSWORD@|$DB_PROXY_PASSWORD|" -e "s|@AUTH_BACKEND_PASSWORD@|$DB_BACKEND_PASSWORD|" "$here/mariadb-init/01-accounts.sql" >"$data/mariadb-init/01-accounts.sql"

# Velocity
v="$data/velocity"
mkdir -p "$v/plugins/authenticator"
cp "$velocity_jar" "$v/plugins/"
[ -f "$v/velocity.toml" ] || cp "$here/velocity.toml" "$v/velocity.toml"
printf '%s' "$FORWARDING_SECRET" >"$v/forwarding.secret"
unzip -p "$velocity_jar" config.yml >"$tmp/velocity-config.yml"
render "$tmp/velocity-config.yml" "$v/plugins/authenticator/config.yml" \
	'database.use=private' \
	'database.endpoints.private.host=mariadb' \
	'database.endpoints.private.user=auth_proxy' \
	"database.endpoints.private.password=\"$DB_PROXY_PASSWORD\"" \
	'database.endpoints.private.ssl-mode=disable' \
	"bridge.secret=\"$BRIDGE_SECRET\"" \
	'routing.auth-servers=[auth]' \
	'routing.lobby-servers=[game]'

# Paper: one AUTH and one GAME server. The settings come out of the built jar: that is the filtered file that ships.
unzip -p "$paper_jar" settings.yml >"$tmp/paper-settings.yml"
paper() {
	local name="$1" role="$2" world="$3" p="$data/$1"
	mkdir -p "$p/plugins/Authenticator"
	cp "$paper_jar" "$p/plugins/"
	render "$tmp/paper-settings.yml" "$p/plugins/Authenticator/settings.yml" \
		"Node_Id=\"$name\"" \
		"Server.Role=$role" \
		'Database.Endpoints.Private.Host="mariadb"' \
		'Database.Endpoints.Private.User="auth_backend"' \
		"Database.Endpoints.Private.Password=\"$DB_BACKEND_PASSWORD\"" \
		'Database.Endpoints.Private.Ssl_Mode=disable' \
		"Bridge.Secret=\"$BRIDGE_SECRET\"" \
		"Login_Spawn.World=\"$world\""
}
paper paper-auth AUTH world
paper paper-game GAME ""

echo
echo "Ready. Start the cluster with:   cd staging && docker compose up"
echo "Then connect a Minecraft client to localhost:25565 and try the scenarios in staging/README.md."
